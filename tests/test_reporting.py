def _rich_done_state() -> ArchitectState:
    """A DONE run carrying one of everything a report can show: a curated
    evidence item AND a web-fallback one, a decision topic WITH evidence and
    one WITHOUT (a verified gap), an ADR with alternatives/consequences, a
    migration step, and a FAILED review with one deterministic and one
    LLM-owned open finding. Realistic Unicode throughout (em dash, accented
    Latin, a checkmark, an arrow) — never CJK, which is not this project's
    content and not covered by the vendored font.
    """
    state = tuf._done_passed_state()
    state.context_record.business_goal = (
        "Sell sneakers online — profitably, at scale (café, naïve résumé)."
    )
    state.context_record.users = ["Shoppers", "Ops team"]
    state.context_record.non_functional_requirements = ["99.9% availability"]
    state.context_record.compliance_requirements = ["GDPR"]
    state.context_record.existing_systems = ["Legacy monolith on EC2"]
    state.context_record.assumptions = ["Traffic peaks 5x on sale days"]
    state.context_record.open_questions = ["Should we support multi-region?"]

    state.decision_topics = [
        DecisionTopic(
            id="TOPIC-1", topic="Event backbone choice",
            query="kafka vs sqs", evidence_ids=["KB-E001"],
        ),
        DecisionTopic(
            id="TOPIC-2", topic="Data consistency strategy",
            query="saga vs 2pc", evidence_ids=[],
        ),
    ]
    state.retrieved_knowledge = [
        KBChunk(
            content="Use event sourcing for auditability and replay.",
            source="Fowler, Enterprise Patterns", page=42, box=1,
            evidence_id="KB-E001",
        ),
        KBChunk(
            content="General web result about microservices trends.",
            source="https://example.com/microservices", page=0, box=3,
            evidence_id="",
        ),
    ]

    state.adrs[0].related_decision_topic_ids = ["TOPIC-1"]
    state.adrs[0].evidence_ids = ["KB-E001"]
    state.adrs[0].context = "We need durable ordering — checkmark: ✓ arrow: →."
    state.adrs[0].rationale = "Kafka gives partition-level ordering and replay."
    state.adrs[0].alternatives_considered = ["Amazon SQS", "RabbitMQ"]
    state.adrs[0].positive_consequences = ["Replayable event log"]
    state.adrs[0].negative_consequences = ["Operational overhead of running Kafka"]

    state.blueprint.data_flows = [
        "Order Service -> Kafka Event Bus: order.created event",
    ]
    state.blueprint.migration_steps = [
        MigrationStep(
            title="Introduce the order event seam",
            objective="Decouple checkout from inventory.",
            changes=["Add Kafka topic order.created"],
            coexistence_or_data_strategy="Monolith and new service both write during transition.",
            exit_condition="100% of orders emit the event with zero data loss.",
        )
    ]
    state.components[0].technology_choices = ["Apache Kafka", "AWS MSK"]

    state.review.issues = [
        ReviewIssue(
            id="DET-1", severity="medium", category="traceability",
            finding="One component has no related ADR.",
            evidence="Kafka Event Bus", suggested_fix="Add related_adr_ids.",
        ),
        ReviewIssue(
            id="LLM-1", severity="high", category="grounding",
            finding="Repo grounding insufficient.",
            evidence="No repo evidence cited.", suggested_fix="Cite specific files.",
        ),
    ]
    state.review.overall_status = "fail"
    state.stopped_on_cap = True
    state.refine_iterations = 3
    state.selected_round = 2
    return state


def _rich_accepted_state(note: str = "Accepted for pilot, tracked in JIRA-123") -> ArchitectState:
    state = _rich_done_state()
    sign_off.accept_design(state, note=note)
    return state


def _extract_pdf_text(pdf_bytes: bytes) -> str:
    reader = PdfReader(BytesIO(pdf_bytes))
    return "\n".join(page.extract_text() or "" for page in reader.pages)


