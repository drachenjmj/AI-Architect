def test_generate_reports_writes_both_files_findable_by_report_paths(tmp_path, monkeypatch):
    monkeypatch.setenv("AI_ARCHITECT_RUNS_DIR", str(tmp_path))
    state = _rich_accepted_state()

    result = reporting.generate_reports(state)

    assert result.ok
    md_path, pdf_path = reporting.report_paths(state.run_id)
    assert md_path == result.markdown_path
    assert pdf_path == result.pdf_path
    assert md_path.read_text(encoding="utf-8").startswith("# AI-Architect Architecture Report")
    assert pdf_path.read_bytes()[:5] == b"%PDF-"


def test_report_files_are_isolated_per_run(tmp_path, monkeypatch):
    monkeypatch.setenv("AI_ARCHITECT_RUNS_DIR", str(tmp_path))
    state_a = _rich_accepted_state()
    state_b = _rich_accepted_state()
    assert state_a.run_id != state_b.run_id

    reporting.generate_reports(state_a)
    assert reporting.report_paths(state_b.run_id) == (None, None)

    reporting.generate_reports(state_b)
    md_a, _ = reporting.report_paths(state_a.run_id)
    md_b, _ = reporting.report_paths(state_b.run_id)
    assert md_a is not None and md_b is not None and md_a != md_b


def test_regenerating_a_run_atomically_replaces_only_its_own_files(tmp_path, monkeypatch):
    monkeypatch.setenv("AI_ARCHITECT_RUNS_DIR", str(tmp_path))
    state = _rich_accepted_state()
    reporting.generate_reports(state)
    md_path, _ = reporting.report_paths(state.run_id)
    first = md_path.read_text(encoding="utf-8")

    state.waiver.note = "MAGIC_UPDATED_NOTE"
    reporting.generate_reports(state)
    second = md_path.read_text(encoding="utf-8")

    assert "MAGIC_UPDATED_NOTE" in second
    assert second != first
    assert not any(p.suffix == ".tmp" for p in md_path.parent.iterdir())


def test_generate_reports_before_acceptance_writes_nothing(tmp_path, monkeypatch):
    monkeypatch.setenv("AI_ARCHITECT_RUNS_DIR", str(tmp_path))
    state = _rich_done_state()  # DONE, not accepted

    result = reporting.generate_reports(state)

    assert not result.markdown_ok and not result.pdf_ok
    assert "ACCEPTED" in result.markdown_error
    assert reporting.report_paths(state.run_id) == (None, None)


def test_pdf_failure_leaves_markdown_intact_and_no_partial_pdf(tmp_path, monkeypatch):
    """The two formats fail INDEPENDENTLY — see the module docstring on
    partial failure. A Markdown write that succeeds is not undone by a PDF
    render that then fails, and no `.tmp` or corrupt target survives it."""
    monkeypatch.setenv("AI_ARCHITECT_RUNS_DIR", str(tmp_path))
    state = _rich_accepted_state()

    def _boom(report):
        raise RuntimeError("MAGIC_PDF_BOOM")

    monkeypatch.setattr(reporting, "render_pdf", _boom)
    result = reporting.generate_reports(state)

    assert result.markdown_ok
    assert not result.pdf_ok
    assert "MAGIC_PDF_BOOM" in result.pdf_error
    md_path, pdf_path = reporting.report_paths(state.run_id)
    assert md_path is not None
    assert pdf_path is None
    assert not any(p.suffix == ".tmp" for p in md_path.parent.iterdir())


def test_report_paths_rejects_a_path_traversal_run_id():
    with pytest.raises(reporting.ReportError):
        reporting.report_paths("../evil")


def test_report_paths_returns_none_for_an_unknown_run(tmp_path, monkeypatch):
    monkeypatch.setenv("AI_ARCHITECT_RUNS_DIR", str(tmp_path))
    assert reporting.report_paths("no-such-run") == (None, None)


