"""test_reporting.py — the canonical report model and both renderers (Kati).

Scope: `pipeline/reporting.py` in isolation — no UI, no AppTest. Three
things are pinned:

  * `build_report` is a PURE, DETERMINISTIC reduction of an ACCEPTED state:
    every value it produces traces back to a field already on the run, a
    FAIL verdict and an open finding survive acceptance unchanged, and
    nothing is generated by an LLM;
  * `render_markdown` and `render_pdf` read ONLY `ReportData` and agree on
    what exists — see the "canonical model" test class;
  * `generate_reports` writes atomically, fails per-format independently,
    and never leaves a partial file or a stray temp file behind.

No network, no LLM: `_rich_accepted_state` is hand-built (same style as
test_sign_off.py's fixtures), and the two agent responses it needs (via
`test_user_feedback._done_passed_state`) are already canned. Every test that
touches disk overrides `AI_ARCHITECT_RUNS_DIR` itself (via `monkeypatch`), on
top of the session-wide redirect in conftest.py, so nothing here ever writes
into a real run history.
"""
