def test_build_report_requires_an_accepted_run():
    """A draft must never impersonate a sign-off — see the module docstring."""
    state = _rich_done_state()
    assert state.stage is Stage.DONE
    with pytest.raises(reporting.ReportError, match="ACCEPTED"):
        reporting.build_report(state)


def test_build_report_is_deterministic():
    state = _rich_accepted_state()
    assert reporting.build_report(state) == reporting.build_report(state)


def test_requirements_and_constraints_preserved_exactly():
    state = _rich_accepted_state()
    report = reporting.build_report(state)
    assert report.context_record == state.context_record


def test_components_data_flows_adrs_migration_steps_preserved():
    state = _rich_accepted_state()
    report = reporting.build_report(state)
    assert report.components == state.components
    assert report.adrs == state.adrs
    assert report.blueprint.data_flows == state.blueprint.data_flows
    assert report.blueprint.migration_steps == state.blueprint.migration_steps
    assert report.features == state.features


def test_evidence_ids_and_provenance_preserved():
    state = _rich_accepted_state()
    report = reporting.build_report(state)
    curated = next(e for e in report.evidence if e.is_curated)
    web = next(e for e in report.evidence if not e.is_curated)
    assert curated.evidence_id == "KB-E001"
    assert curated.source == "Fowler, Enterprise Patterns"
    assert curated.page == 42
    assert web.evidence_id == ""
    assert web.source == "https://example.com/microservices"


def test_reviewer_verdict_and_findings_preserved():
    state = _rich_accepted_state()
    report = reporting.build_report(state)
    assert report.review == state.review
    origins = {f.id: f.origin for f in report.findings}
    assert origins == {"DET-1": "deterministic", "LLM-1": "llm"}


def test_finding_origin_falls_back_to_unknown_for_an_unrecognised_prefix():
    state = _rich_done_state()
    state.review.issues = [
        ReviewIssue(id="OTHER-1", severity="low", finding="Something else.")
    ]
    sign_off.accept_design(state)
    report = reporting.build_report(state)
    assert report.findings[0].origin == "unknown"


def test_unresolved_findings_and_kb_gaps_are_not_hidden_by_acceptance():
    """Acceptance means a human took the design — not that the record forgets
    what it was taken despite (see pipeline/sign_off.py)."""
    state = _rich_accepted_state()
    report = reporting.build_report(state)

    assert {f.id for f in report.findings} == {"DET-1", "LLM-1"}
    assert [t.id for t in report.decision_topics if t.has_gap] == ["TOPIC-2"]
    assert any("TOPIC-2" in item for item in report.limitations.evidence_gaps)
    assert any("LLM-1" in item for item in report.limitations.unresolved_high)
    assert any("DET-1" in item for item in report.limitations.unresolved_medium)
    assert report.waiver is not None
    assert set(report.waiver.finding_ids) == {"DET-1", "LLM-1"}


def test_traceability_maps_are_exact_id_matches_only():
    state = _rich_accepted_state()
    report = reporting.build_report(state)
    trace = report.traceability
    assert trace.feature_to_adrs["FEAT-001"] == ["ADR-001"]
    assert trace.feature_to_components["FEAT-001"] == ["COMP-001"]
    assert trace.decision_topic_to_adrs["TOPIC-1"] == ["ADR-001"]
    assert trace.decision_topic_to_adrs["TOPIC-2"] == []
    assert trace.adr_to_evidence["ADR-001"] == ["KB-E001"]


def test_executive_summary_prefers_the_blueprint_stakeholder_view():
    state = _rich_accepted_state()
    report = reporting.build_report(state)
    assert report.executive_summary == state.blueprint.stakeholder_view.strip()


def test_executive_summary_falls_back_to_a_deterministic_combination():
    state = _rich_done_state()
    state.blueprint.stakeholder_view = ""
    sign_off.accept_design(state)
    report = reporting.build_report(state)

    assert state.context_record.business_goal.strip() in report.executive_summary
    assert state.context_record.problem_statement.strip() in report.executive_summary
    assert "FAIL" in report.executive_summary


def test_no_fabricated_content_beyond_the_executive_summary_combination():
    """Every OTHER field on `ReportData` is a passthrough or a deterministic
    ID-keyed map — never a new sentence the state itself does not contain."""
    state = _rich_accepted_state()
    report = reporting.build_report(state)
    assert report.blueprint == state.blueprint
    assert report.review == state.review
    assert report.context_record == state.context_record


